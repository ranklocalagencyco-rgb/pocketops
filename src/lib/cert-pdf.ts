/** Generic certificate PDF renderer — used by the app and the client hub. */
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import type { certificates, customers, tenants } from '../db/schema';
import { CERT_DEFS } from './certs';
import { fmtDateTz } from './jobs';

type Cert = typeof certificates.$inferSelect;
type Tenant = typeof tenants.$inferSelect;
type Customer = typeof customers.$inferSelect;

function wrap(text: string, max = 92): string[] {
  const out: string[] = [];
  for (const rawLine of text.split(/\r?\n/)) {
    let line = rawLine;
    while (line.length > max) {
      let cut = line.lastIndexOf(' ', max);
      if (cut <= 0) cut = max;
      out.push(line.slice(0, cut));
      line = line.slice(cut).trimStart();
    }
    out.push(line);
  }
  return out;
}

export async function renderCertPdf(
  cert: Cert,
  tenant: Tenant | undefined,
  customer: Customer | undefined,
  jobTitle: string,
): Promise<Uint8Array> {
  const def = CERT_DEFS[cert.type];
  const data = JSON.parse(cert.data) as Record<string, string>;

  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595, 842]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.1, 0.09, 0.08);
  const grey = rgb(0.45, 0.42, 0.4);
  const copper = rgb(0.91, 0.45, 0.1);
  let y = 790;
  const text = (s: string, x: number, size = 10, f = font, color = ink) =>
    page.drawText(s, { x, y, size, font: f, color });

  text(def.title.toUpperCase(), 50, 16, bold, copper);
  y -= 16;
  text(`Certificate no. ${cert.certNumber} · Issued ${fmtDateTz(cert.issuedAt, tenant?.timezone)}`, 50, 9, font, grey);

  y -= 28;
  text(tenant?.name ?? '', 50, 12, bold);
  y -= 13;
  for (const l of [tenant?.phone, tenant?.email, tenant?.vatNumber ? `VAT No. ${tenant.vatNumber}` : null]) {
    if (l) { text(l, 50, 9, font, grey); y -= 11; }
  }
  if (cert.registrationNumber) {
    text(`${def.regLabel} ${cert.registrationNumber}`, 50, 9, font, grey);
    y -= 11;
  }

  y -= 10;
  text('Site / customer', 50, 9, bold, grey);
  y -= 13;
  text(customer?.name ?? '', 50, 11, bold);
  y -= 12;
  const site = [customer?.addressLine1, customer?.city, customer?.region, customer?.postalCode]
    .filter(Boolean)
    .join(', ');
  if (site) { text(site, 50, 9, font, grey); y -= 12; }
  text(`Job: ${jobTitle}`, 50, 9, font, grey);

  y -= 14;
  page.drawLine({ start: { x: 50, y }, end: { x: 545, y }, thickness: 0.8, color: copper });
  y -= 20;

  for (const field of def.fields) {
    const value = (data[field.key] ?? '').trim();
    if (!value) continue;
    text(field.label.replace(/\s*\(.*\)$/, '').toUpperCase(), 50, 8, bold, grey);
    y -= 13;
    for (const line of wrap(value)) {
      text(line, 50, 10);
      y -= 13;
      if (y < 120) break;
    }
    y -= 8;
    if (y < 120) break;
  }

  y = 90;
  page.drawLine({ start: { x: 50, y }, end: { x: 280, y }, thickness: 0.5, color: grey });
  y -= 12;
  text(`${cert.engineerName} — ${fmtDateTz(cert.issuedAt, tenant?.timezone)}`, 50, 9);
  y -= 12;
  text('Engineer / operative', 50, 8, font, grey);
  y = 50;
  text('Generated by Pocket Ops', 50, 8, font, grey);

  return pdf.save();
}
